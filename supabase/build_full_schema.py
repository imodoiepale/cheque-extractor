#!/usr/bin/env python3
"""
Build supabase/FULL_SCHEMA.sql: one script that recreates the whole Kyriq
database on an empty Supabase project, from supabase/migrations/.

    python supabase/build_full_schema.py          # write FULL_SCHEMA.sql
    python supabase/build_full_schema.py --check  # exit 1 if it is out of date

Paste FULL_SCHEMA.sql into the Supabase SQL editor (or `psql -f`) once. It runs
in a single transaction, so a failure leaves nothing half-applied, and every
migration is idempotent, so running it a second time is harmless.

Order is the migration number, then the file name (039 exists twice and the
two touch different things). The migrations stay the source of truth: never
edit FULL_SCHEMA.sql by hand. supabase/verify_full_schema.py replays it into a
scratch Postgres, twice, to prove it.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MIGRATIONS = HERE / "migrations"
OUT = HERE / "FULL_SCHEMA.sql"

HEADER = """-- Kyriq: complete database, recreated from supabase/migrations/{first} to {last}.
--
-- Run this ONCE on an empty Supabase project (SQL editor, or psql -f). It needs
-- the standard Supabase objects (auth.users, storage.buckets, the anon /
-- authenticated / service_role roles), which every Supabase project has.
--
-- One transaction: if any statement fails nothing is applied and the error says
-- which migration it came from. Every migration is idempotent, so a second run
-- changes nothing. Generated by supabase/build_full_schema.py; do not edit.
-- {count} migrations.

BEGIN;
"""


def migration_files():
    files = sorted(
        MIGRATIONS.glob("*.sql"),
        key=lambda p: (int(re.match(r"(\d+)", p.name).group(1)), p.name),
    )
    assert files, f"no migrations in {MIGRATIONS}"
    return files


def build():
    files = migration_files()
    parts = [HEADER.format(first=files[0].stem, last=files[-1].stem, count=len(files))]
    for f in files:
        body = f.read_text(encoding="utf-8").replace("\r\n", "\n").strip("\n")
        # A migration's own transaction control would end ours early.
        stripped = re.sub(r"(?im)^\s*(begin|commit)\s*;\s*$", "-- (transaction control removed) \\1;", body)
        parts.append(
            "\n-- " + "=" * 72 + f"\n-- {f.name}\n-- " + "=" * 72 + "\n" + stripped + "\n"
        )
    parts.append("\nCOMMIT;\n")
    return "".join(parts)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("FULL_SCHEMA.sql is out of date: run python supabase/build_full_schema.py")
            sys.exit(1)
        print("FULL_SCHEMA.sql is up to date")
    else:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(HERE.parent)}: {len(migration_files())} migrations, {len(text.splitlines())} lines")
