#!/usr/bin/env python3
"""
Build supabase/FULL_SCHEMA.sql: one script that recreates the whole Kyriq
database on an empty Supabase project.

    python supabase/build_full_schema.py                    # write FULL_SCHEMA.sql
    python supabase/build_full_schema.py --check            # exit 1 if it is out of date
    python supabase/build_full_schema.py --migrations-only  # NOT a rebuild, see below

THE MIGRATIONS ALONE CANNOT REBUILD THE DATABASE. The live project was started
before migration 001 and patched by hand: tables such as user_profiles and
app_settings, and columns such as integrations.user_id, exist only there, and
migrations 005, 008, 009, 010, 011, 013 and others reference them. A replay of
001..046 into an empty database fails in about a dozen places (run
supabase/verify_full_schema.py to see them).

So the full script is  BASELINE + every migration after it, where the baseline
is a schema-only dump of the live database, taken once:

    pg_dump --schema-only --no-owner --no-privileges --schema=public \
        "$SUPABASE_DB_URL" > supabase/baseline/baseline.sql
    echo 046 > supabase/baseline/applies_through.txt

(SUPABASE_DB_URL is the connection string under Project Settings > Database.
It contains the database password: keep it out of git and out of chat.)
See supabase/FULL_SCHEMA_README.md.

FULL_SCHEMA.sql runs in a single transaction, so a failure leaves nothing
half-applied. supabase/verify_full_schema.py replays it into a scratch Postgres,
twice, to prove it. Never edit FULL_SCHEMA.sql by hand.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MIGRATIONS = HERE / "migrations"
OUT = HERE / "FULL_SCHEMA.sql"
BASELINE = HERE / "baseline" / "baseline.sql"
APPLIES_THROUGH = HERE / "baseline" / "applies_through.txt"

HEADER = """-- Kyriq: complete database ({baseline_note}).
--
-- Run this ONCE on an empty Supabase project (SQL editor, or psql -f). It needs
-- the standard Supabase objects (auth.users, storage.buckets, the anon /
-- authenticated / service_role roles), which every Supabase project has.
--
-- One transaction: if any statement fails nothing is applied. Generated by
-- supabase/build_full_schema.py; do not edit.
-- {count} migrations after the baseline: {first} to {last}.

BEGIN;
"""

NO_BASELINE = (
    "No baseline. The migrations alone cannot rebuild this database (see the docstring of\n"
    "supabase/build_full_schema.py). Take a schema-only dump of the live database into\n"
    "supabase/baseline/baseline.sql and write the last migration number it already\n"
    "contains into supabase/baseline/applies_through.txt.\n"
    "--migrations-only builds a partial script that will not pass the verifier."
)


def number(path):
    return int(re.match(r"(\d+)", path.name).group(1))


def migration_files():
    files = sorted(MIGRATIONS.glob("*.sql"), key=lambda p: (number(p), p.name))
    assert files, f"no migrations in {MIGRATIONS}"
    return files


def banner(name):
    return "\n-- " + "=" * 72 + f"\n-- {name}\n-- " + "=" * 72 + "\n"


def build(migrations_only=False):
    files = migration_files()
    baseline = ""
    if migrations_only:
        note = "NO BASELINE: not a rebuild of the live schema"
    else:
        if not BASELINE.exists() or not APPLIES_THROUGH.exists():
            sys.exit(NO_BASELINE)
        through = int(APPLIES_THROUGH.read_text().strip())
        files = [f for f in files if number(f) > through]
        note = f"live schema baseline through migration {through:03d}"
        baseline = BASELINE.read_text(encoding="utf-8").replace("\r\n", "\n").strip("\n")

    parts = [HEADER.format(
        baseline_note=note, count=len(files),
        first=files[0].stem if files else "-", last=files[-1].stem if files else "-",
    )]
    if baseline:
        parts.append(banner("000_baseline.sql (live schema dump)") + baseline + "\n")
    for f in files:
        body = f.read_text(encoding="utf-8").replace("\r\n", "\n").strip("\n")
        # A migration's own transaction control would end ours early.
        body = re.sub(r"(?im)^\s*(begin|commit)\s*;\s*$", r"-- (transaction control removed) \1;", body)
        parts.append(banner(f.name) + body + "\n")
    parts.append("\nCOMMIT;\n")
    return "".join(parts)


if __name__ == "__main__":
    text = build(migrations_only="--migrations-only" in sys.argv)
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("FULL_SCHEMA.sql is out of date: run python supabase/build_full_schema.py")
            sys.exit(1)
        print("FULL_SCHEMA.sql is up to date")
    else:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(HERE.parent)}: {len(text.splitlines())} lines")
